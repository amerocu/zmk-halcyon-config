#include <lvgl.h>

#define WHITE 0xff, 0xff, 0xff, 0xff
#define BLACK 0x00, 0x00, 0x00, 0xff

#define IMAGE(name, size, row_stride)                                                              \
    const lv_image_dsc_t name = {                                                                  \
        .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_I1,                         \
                   .w = size, .h = size, .stride = row_stride},                                    \
        .data_size = sizeof(name##_map), .data = name##_map,                                        \
    }

/* Upstream's white variants have identical pixels and reversed palettes. */
#define MODIFIER(name, ...)                                                                        \
    static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t name##_small_map[] = {     \
        WHITE, BLACK, __VA_ARGS__};                                                                \
    static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t name##_small_white_map[] = { \
        BLACK, WHITE, __VA_ARGS__};                                                                \
    IMAGE(name##_small, 14, 2);                                                                    \
    IMAGE(name##_small_white, 14, 2)

